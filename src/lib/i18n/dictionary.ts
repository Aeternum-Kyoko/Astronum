/**
 * Ordinal for a house number: "7th" in English. Hindi needs the oblique form before a postposition
 * ("सातवें भाव में") and the direct form on its own ("सातवाँ भाव").
 */
export function ordinalFor(locale: Locale, n: number, form: "oblique" | "direct" = "oblique"): string {
  if (locale === "hi") {
    const oblique = ["पहले", "दूसरे", "तीसरे", "चौथे", "पाँचवें", "छठे", "सातवें", "आठवें", "नौवें", "दसवें", "ग्यारहवें", "बारहवें"];
    const direct = ["पहला", "दूसरा", "तीसरा", "चौथा", "पाँचवाँ", "छठा", "सातवाँ", "आठवाँ", "नौवाँ", "दसवाँ", "ग्यारहवाँ", "बारहवाँ"];
    return (form === "direct" ? direct : oblique)[n - 1];
  }
  return `${n}${n === 1 ? "st" : n === 2 ? "nd" : n === 3 ? "rd" : "th"}`;
}
